/**
 * Patterns for labels and sentences with a variable part. Each entry: [pattern, Spanish template].
 * In the template, $1 and $2 are the parts that the pattern captured. A part in {braces} is
 * translated again (for example a network name), so "{1}" means "translate capture 1".
 * @type {ReadonlyArray<readonly [RegExp, string]>}
 */
export const ES_PATTERNS = Object.freeze([
  [/^This looks like ([^.]+), but the checksum is wrong\.$/, 'Esto parece {1}, pero la suma de verificación es incorrecta.'],
  [/^Same key on ([^.]+) and ([^.]+)\.$/, 'La misma clave en $1 y $2.'],
  [/^Token contract: (.+) on (.+)$/, 'Contrato del token: $1 en $2'],
  [/^Token contract: (.+)$/, 'Contrato del token: $1'],
  [/^Program: (.+)$/, 'Programa: {1}'],
  [/^Unknown Bech32 address \((.+)\)$/, 'Dirección Bech32 desconocida ($1)'],
  [/^SegWit v(\d+) \(future type\)$/, 'SegWit v$1 (tipo futuro)'],
  [/^Tezos account \((.+)\)$/, 'Cuenta de Tezos ($1)'],
  [/^Substrate network \(prefix (\d+)\)$/, 'Red Substrate (prefijo $1)'],
  // Labels never end with a period, so these patterns cannot match a sentence.
  [/^(.+) test address$/, 'Dirección de prueba de {1}'],
  [/^(.+) script address$/, 'Dirección de script de {1}'],
  [/^(.+) account$/, 'Cuenta de {1}'],
  [/^(.+) address$/, 'Dirección de {1}'],
]);
